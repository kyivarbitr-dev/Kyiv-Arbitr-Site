#!/usr/bin/env python3
"""Окремі сторінки новин, RSS-стрічка і записи в sitemap.xml — з news/news.json.

Для кожної новини, дата якої вже настала (за Києвом), створює news/<id>.html на основі
оформлення сторінки news.html (шапка, меню, підвал). Новини з майбутньою датою з'являються
в свій день (скрипт щогодини запускає GitHub Actions разом із публікацією в Telegram).

  python scripts/build_news.py
"""
from __future__ import annotations

import html
import json
import re
from datetime import datetime
from email.utils import format_datetime
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parent.parent
NEWS_JSON = ROOT / "news" / "news.json"
TEMPLATE = ROOT / "news.html"
OUT_DIR = ROOT / "news"
RSS = OUT_DIR / "rss.xml"
SITEMAP = ROOT / "sitemap.xml"
SITE = "https://kyivarbitr.com.ua"
TG = "https://t.me/kyivarbitr_ua"
KYIV = ZoneInfo("Europe/Kyiv")
MONTHS = ["січня", "лютого", "березня", "квітня", "травня", "червня", "липня", "серпня",
          "вересня", "жовтня", "листопада", "грудня"]
ID_RX = re.compile(r"^[\w-]+$")
GEN_MARK = "<!-- generated by scripts/build_news.py -->"


def esc(s) -> str:
    return html.escape(str(s or ""), quote=True)


def nb(s: str) -> str:
    """Нерозривний пробіл після коротких слів, як у решті сайту."""
    return re.sub(r"(?<=\s)(\w{1,2}) ", lambda m: m.group(1) + "&nbsp;", s)


def date_uk(d: str) -> str:
    y, m, dd = d.split("-")
    return f"{int(dd)} {MONTHS[int(m) - 1]} {y}"


def short(s: str, n: int) -> str:
    s = re.sub(r"\s+", " ", s or "").strip()
    return s if len(s) <= n else s[: n - 1].rsplit(" ", 1)[0] + "…"


def body_html(text: str) -> str:
    out = []
    for par in re.split(r"\n{2,}", text or ""):
        par = par.strip()
        if not par:
            continue
        lines = [nb(esc(x)) for x in par.split("\n")]
        out.append("<p>" + "<br>".join(lines) + "</p>")
    return "\n        ".join(out)


def links_html(n: dict) -> str:
    items = n.get("links") or [{"url": n.get("link"), "label": n.get("linkLabel")}]
    out = []
    for x in items:
        u = (x or {}).get("url")
        if isinstance(u, str) and u.startswith(("http://", "https://")):
            out.append(f'<a class="news-link" href="{esc(u)}" target="_blank" rel="noopener">{esc(x.get("label") or "Джерело")} →</a>')
    return "\n          ".join(out)


def split_template():
    t = TEMPLATE.read_text(encoding="utf-8")
    head, rest = t.split("<main>", 1)
    _, foot = rest.split("</main>", 1)
    return head, foot


def page(n: dict, head: str, foot: str, others: list) -> str:
    nid, title, summary = n["id"], n.get("title") or "", n.get("summary") or ""
    url = f"{SITE}/news/{nid}"
    img = n.get("image") if isinstance(n.get("image"), str) and re.fullmatch(r"[\w\-/.]+\.(jpe?g|png|webp)", n.get("image") or "", re.I) else None
    img_abs = f"{SITE}/news/{img}" if img else f"{SITE}/assets/og-image.jpg"
    desc = short(summary, 160)
    h = head
    h = h.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<base href="/">', 1)
    h = re.sub(r"<title>.*?</title>", f"<title>{esc(short(title, 90))} · Раковський О. П.</title>", h, count=1, flags=re.S)
    h = re.sub(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{esc(desc)}">', h, count=1)
    h = h.replace('<meta property="og:type" content="website">', '<meta property="og:type" content="article">')
    h = re.sub(r'<meta property="og:title" content="[^"]*">', f'<meta property="og:title" content="{esc(title)}">', h, count=1)
    h = re.sub(r'<meta property="og:description" content="[^"]*">', f'<meta property="og:description" content="{esc(desc)}">', h, count=1)
    h = re.sub(r'<meta property="og:image" content="[^"]*">', f'<meta property="og:image" content="{esc(img_abs)}">', h, count=1)
    h = re.sub(r'<meta property="og:image:alt" content="[^"]*">', f'<meta property="og:image:alt" content="{esc(n.get("image_alt") or title)}">', h, count=1)
    h = re.sub(r'<link rel="canonical" href="[^"]*">', f'<link rel="canonical" href="{url}">', h, count=1)
    h = re.sub(r'<link rel="alternate" hreflang="[^"]*" href="[^"]*">\n', "", h)
    h = re.sub(r'<meta property="og:url" content="[^"]*">', f'<meta property="og:url" content="{url}">', h, count=1)
    h = h.replace('<script src="js/news.js" defer></script>\n', "")
    h = h.replace('<a href="news.html" lang="uk" hreflang="uk" aria-current="true">UA</a>',
                  f'<a href="news/{nid}.html" lang="uk" hreflang="uk" aria-current="true">UA</a>')
    ld = {
        "@context": "https://schema.org", "@type": "NewsArticle", "headline": short(title, 110),
        "description": desc, "datePublished": n["date"], "dateModified": n["date"], "inLanguage": "uk",
        "image": [img_abs], "mainEntityOfPage": url,
        "author": {"@type": "Person", "@id": f"{SITE}/#person", "name": "Раковський Олексій Павлович", "url": f"{SITE}/"},
        "publisher": {"@type": "Person", "@id": f"{SITE}/#person", "name": "Раковський Олексій Павлович"},
    }
    h = h.replace("</head>", '<link rel="alternate" type="application/rss+xml" title="Новини · Раковський О. П." href="news/rss.xml">\n'
                  '<script type="application/ld+json">' + json.dumps(ld, ensure_ascii=False) + "</script>\n</head>", 1)

    fig = (f'<figure class="news-hero"><img src="news/{esc(img)}" alt="{esc(n.get("image_alt") or title)}" width="1200" height="630"></figure>'
           if img else "")
    more = "\n".join(
        f'          <li><a href="news/{esc(o["id"])}.html"><time datetime="{esc(o["date"])}">{date_uk(o["date"])}</time>'
        f'<span>{nb(esc(o["title"]))}</span></a></li>' for o in others)
    tag = f'<span class="news-tag">{esc(n.get("tag"))}</span>' if n.get("tag") else ""
    main = f"""<main>
{GEN_MARK}
<section id="news">
  <div class="wrap news-page">
    <nav class="crumbs" aria-label="Навігація"><a href="news.html">Новини</a><span aria-hidden="true">/</span><span>{esc(n.get("tag") or "Новина")}</span></nav>
    <article>
      <div class="news-meta"><time datetime="{esc(n["date"])}">{date_uk(n["date"])}</time>{tag}</div>
      <h1>{nb(esc(title))}</h1>
      <p class="lead">{nb(esc(summary))}</p>
      {fig}
      <div class="news-text">
        {body_html(n.get("text") or "")}
      </div>
      <div class="news-links">
          {links_html(n)}
      </div>
    </article>
    <aside class="tg-cta">
      <p><b>Новини, лоти й&nbsp;думка&nbsp;— першими в&nbsp;Telegram.</b> Щоранку добірка лотів банкрутства з&nbsp;прапорцями ризиків і&nbsp;нові матеріали сайту.</p>
      <a class="btn btn-primary" href="{TG}" target="_blank" rel="noopener">Підписатися на&nbsp;канал</a>
    </aside>
    <section class="news-more" aria-label="Інші новини">
      <h2 class="sub-h">Інші новини</h2>
      <ul>
{more}
      </ul>
      <p><a class="news-link" href="news.html">Усі новини →</a></p>
    </section>
    <p class="note">Матеріал має загальний інформаційний характер і&nbsp;не&nbsp;є юридичною консультацією. Норми законодавства перевіряйте в&nbsp;актуальній редакції.</p>
  </div>
</section>
</main>"""
    return h + main + foot


def rss(items: list) -> str:
    # дата останньої новини, а не «зараз»: інакше файл змінювався б щогодини без нових матеріалів
    now = format_datetime(datetime.fromisoformat(items[0]["date"]).replace(hour=9, tzinfo=KYIV)) if items else ""
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">', "<channel>",
           "<title>Новини · Раковський О. П., арбітражний керуючий</title>",
           f"<link>{SITE}/news</link>",
           "<description>Банкрутство, борги, торги Prozorro.Продажі, фінанси й законодавство.</description>",
           "<language>uk</language>", f"<lastBuildDate>{now}</lastBuildDate>",
           f'<atom:link href="{SITE}/news/rss.xml" rel="self" type="application/rss+xml"/>']
    for n in items[:30]:
        d = datetime.fromisoformat(n["date"]).replace(hour=9, tzinfo=KYIV)
        url = f"{SITE}/news/{n['id']}"
        out += ["<item>", f"<title>{esc(n['title'])}</title>", f"<link>{url}</link>", f'<guid isPermaLink="true">{url}</guid>',
                f"<pubDate>{format_datetime(d)}</pubDate>", f"<description>{esc(n.get('summary') or '')}</description>"]
        if n.get("tag"):
            out.append(f"<category>{esc(n['tag'])}</category>")
        img = n.get("image")
        if isinstance(img, str) and re.fullmatch(r"[\w\-/.]+\.jpe?g", img, re.I):
            p = OUT_DIR / img
            size = p.stat().st_size if p.exists() else 0
            out.append(f'<enclosure url="{SITE}/news/{esc(img)}" type="image/jpeg" length="{size}"/>')
        out.append("</item>")
    out += ["</channel>", "</rss>", ""]
    return "\n".join(out)


def update_sitemap(items: list):
    xml = SITEMAP.read_text(encoding="utf-8")
    block = "  <!-- news:start -->\n" + "".join(
        f"  <url>\n    <loc>{SITE}/news/{n['id']}</loc>\n    <lastmod>{n['date']}</lastmod>\n  </url>\n" for n in items
    ) + "  <!-- news:end -->\n"
    if "<!-- news:start -->" in xml:
        xml = re.sub(r"  <!-- news:start -->.*?<!-- news:end -->\n", lambda m: block, xml, flags=re.S)
    else:
        xml = xml.replace("</urlset>", block + "</urlset>")
    SITEMAP.write_text(xml, encoding="utf-8")


def main():
    today = datetime.now(KYIV).strftime("%Y-%m-%d")
    news = json.loads(NEWS_JSON.read_text(encoding="utf-8"))
    items = [n for n in news if isinstance(n, dict) and n.get("id") and ID_RX.match(str(n["id"]))
             and n.get("title") and str(n.get("date", "9999")) <= today]
    items.sort(key=lambda n: (n["date"], n["id"]), reverse=True)
    head, foot = split_template()
    keep = set()
    for i, n in enumerate(items):
        others = [o for o in items if o["id"] != n["id"]][:4]
        path = OUT_DIR / f"{n['id']}.html"
        path.write_text(page(n, head, foot, others), encoding="utf-8")
        keep.add(path.name)
    # прибрати сторінки новин, яких більше немає в news.json (лише згенеровані цим скриптом)
    for p in OUT_DIR.glob("*.html"):
        if p.name not in keep and GEN_MARK in p.read_text(encoding="utf-8"):
            p.unlink()
    RSS.write_text(rss(items), encoding="utf-8")
    update_sitemap(items)
    print(f"Новини: сторінок {len(items)}, RSS і sitemap оновлено")


if __name__ == "__main__":
    main()
